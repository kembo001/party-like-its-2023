/* ---------- Music player (main.html) ---------- */
function initMusicPlayer() {
  var audio;
  var playPauseBtn = document.getElementById('playPauseBtn');
  var stopBtn = document.getElementById('stopBtn');
  var scrollingText = document.getElementById('scrollingText');
  var currentSongIndex = 0;

  if (!playPauseBtn || !scrollingText) return;

  var playlist = [
    {
      title: 'The Stars Keep On Calling My Name',
      src: 'music/The Stars Keep On Calling My Name.mp3'
    },

    {
      title: 'Please Shut Up',
      src: 'music/music-intro.mp3'
    }
  ];

  // One audio element for the whole playlist, so the "ended" handler
  // below keeps working for every song, not just the first.
  audio = new Audio();

  function loadSong(index) {
    audio.src = playlist[index].src;
    scrollingText.textContent = playlist[index].title;
    scrollingText.setAttribute('data-track', playlist[index].title);
  }

  loadSong(currentSongIndex);

  playPauseBtn.addEventListener('click', function () {
    if (audio.paused) {
      audio.play();
      playPauseBtn.textContent = 'Pause';
      scrollingText.classList.add('scrolling-animation');
    } else {
      audio.pause();
      playPauseBtn.textContent = 'Play';
      scrollingText.classList.remove('scrolling-animation');
    }
  });

  if (stopBtn) {
    stopBtn.addEventListener('click', function () {
      audio.pause();
      audio.currentTime = 0;
      playPauseBtn.textContent = 'Play';
      scrollingText.classList.remove('scrolling-animation');
    });
  }

  audio.addEventListener('ended', function () {
    currentSongIndex = (currentSongIndex + 1) % playlist.length;
    loadSong(currentSongIndex);
    audio.play();
  });
}

/* ---------- Photo lightbox (main.html) ---------- */
function initLightbox() {
  var modal = document.getElementById('myModal');
  var modalImg = document.getElementById('modalImg');
  var caption = document.getElementById('modalCaption');
  var count = document.getElementById('modalCount');
  var closeBtn = document.getElementById('modalClose');
  var prevBtn = document.getElementById('prevBtn');
  var nextBtn = document.getElementById('nextBtn');
  if (!modal || !modalImg || !closeBtn) return;

  // One entry per photo on the page, in page order.
  var photos = Array.prototype.slice.call(
    document.querySelectorAll('.gallery-item img, .polaroid img')
  );
  var currentIndex = 0;
  var lastFocused = null;

  function captionFor(img) {
    var polaroid = img.closest('.polaroid');
    if (polaroid) {
      var figcaption = polaroid.querySelector('figcaption');
      if (figcaption) return figcaption.textContent.trim();
    }
    var win = img.closest('.window');
    var title = win && win.querySelector('.title-bar__title');
    return title ? title.textContent.trim() : 'Photo';
  }

  function show(index) {
    currentIndex = (index + photos.length) % photos.length;
    var img = photos[currentIndex];
    modalImg.src = img.currentSrc || img.src;
    modalImg.alt = img.alt;
    if (caption) caption.textContent = captionFor(img);
    if (count) count.textContent = (currentIndex + 1) + ' / ' + photos.length;
  }

  function open(index) {
    lastFocused = document.activeElement;
    show(index);
    modal.style.display = 'flex';
    document.body.classList.add('modal-open');
    closeBtn.focus();
  }

  function close() {
    modal.style.display = 'none';
    document.body.classList.remove('modal-open');
    if (lastFocused && lastFocused.focus) lastFocused.focus();
  }

  function isOpen() {
    return modal.style.display === 'flex';
  }

  photos.forEach(function (img, index) {
    img.setAttribute('tabindex', '0');
    img.setAttribute('role', 'button');
    if (!img.getAttribute('aria-label')) {
      img.setAttribute('aria-label', 'Open photo: ' + captionFor(img));
    }
    img.addEventListener('click', function (e) {
      e.preventDefault();
      open(index);
    });
    img.addEventListener('keydown', function (e) {
      if (e.key === 'Enter' || e.key === ' ') {
        e.preventDefault();
        open(index);
      }
    });
  });

  if (prevBtn) prevBtn.addEventListener('click', function () { show(currentIndex - 1); });
  if (nextBtn) nextBtn.addEventListener('click', function () { show(currentIndex + 1); });
  closeBtn.addEventListener('click', close);

  modal.addEventListener('click', function (e) {
    if (e.target === modal) close();
  });

  document.addEventListener('keydown', function (e) {
    if (!isOpen()) return;
    if (e.key === 'Escape') close();
    else if (e.key === 'ArrowLeft') show(currentIndex - 1);
    else if (e.key === 'ArrowRight') show(currentIndex + 1);
  });
}

/* ---------- Password page (index.html) ---------- */
function checkPassword() {
  var enteredPassword = document.getElementById("password").value;
  var correctPassword = "NucleicAcids";

  if (enteredPassword === correctPassword) {
    window.location.href = "main.html";
  } else {
    var modal = document.getElementById("customModal");
    modal.style.display = "flex";
    document.getElementById("modalImage").src = "img/adventure-time-bmo-game-over-aft70vderh10hupg.gif";
    var ok = modal.querySelector('.error-dialog__actions [data-close-modal]');
    if (ok) ok.focus();
  }
}

function initLogin() {
  var form = document.getElementById('loginForm');
  var modal = document.getElementById('customModal');
  if (!form || !modal) return;

  form.addEventListener('submit', function (e) {
    e.preventDefault();
    checkPassword();
  });

  function closeError() {
    modal.style.display = 'none';
    var input = document.getElementById('password');
    if (input) {
      input.focus();
      input.select();
    }
  }

  Array.prototype.forEach.call(modal.querySelectorAll('[data-close-modal]'), function (btn) {
    btn.addEventListener('click', closeError);
  });

  modal.addEventListener('click', function (e) {
    if (e.target === modal) closeError();
  });

  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape' && modal.style.display === 'flex') closeError();
  });
}

/* ---------- Taskbar clock: today's time, but it's always 2023 ---------- */
function initTaskbarClock() {
  var timeEl = document.getElementById('taskbarTime');
  var dateEl = document.getElementById('taskbarDate');
  if (!timeEl) return;

  function tick() {
    var now = new Date();
    timeEl.textContent = now.toLocaleTimeString([], { hour: 'numeric', minute: '2-digit' });
    if (dateEl) dateEl.textContent = (now.getMonth() + 1) + '/' + now.getDate() + '/2023';
  }

  tick();
  setInterval(tick, 15000);
}

/* ---------- Hit counter (counts this browser's visits, starting at 2023) ---------- */
function initVisitorCounter() {
  var counter = document.getElementById('visitorCount');
  if (!counter) return;

  var visits = 1;
  try {
    visits = parseInt(localStorage.getItem('pli2023-visits') || '0', 10) + 1;
    localStorage.setItem('pli2023-visits', String(visits));
  } catch (e) {
    visits = 1;
  }

  var digits = String(2022 + visits).padStart(6, '0').split('');
  counter.innerHTML = '';
  digits.forEach(function (d) {
    var span = document.createElement('span');
    span.textContent = d;
    counter.appendChild(span);
  });
}

/* ---------- Sparkle cursor trail ---------- */
function initSparkles() {
  if (!window.matchMedia) return;
  if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  if (!window.matchMedia('(pointer: fine)').matches) return;

  var chars = ['✦', '✧', '★', '✶'];
  var colors = ['#ffffff', '#FFCDFA', '#FF98F5', '#ffe14d', '#99ffff'];
  var last = 0;

  document.addEventListener('pointermove', function (e) {
    var now = performance.now();
    if (now - last < 45) return;
    last = now;

    var s = document.createElement('span');
    s.className = 'sparkle';
    s.setAttribute('aria-hidden', 'true');
    s.textContent = chars[Math.floor(Math.random() * chars.length)];
    s.style.left = e.clientX + 'px';
    s.style.top = e.clientY + 'px';
    s.style.color = colors[Math.floor(Math.random() * colors.length)];
    s.style.setProperty('--dx', (Math.random() * 30 - 15).toFixed(1) + 'px');
    s.addEventListener('animationend', function () { s.remove(); });
    document.body.appendChild(s);
  });
}
